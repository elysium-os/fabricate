use crate::config::{Config, DepStyle};

pub const BUILTIN_VARIABLES: &'static [&'static str] = &["depfile"];
pub const RESERVED_VARIABLES: &'static [&'static str] = &["in", "out"];

fn ninja_escape(str: &str, escape_var: bool) -> String {
    let mut str = str.to_string();
    if escape_var {
        str = str.replace("$", "$$");
    }
    str = str.replace(" ", "$ ");
    str = str.replace(":", "$:");
    str = str.replace("\n", "$\n");
    str
}

pub fn build_file(config: &Config) -> String {
    let mut ninja_data = String::new();

    ninja_data.push_str("# DO NOT TOUCH\n");
    ninja_data.push_str("# Generated by Fabricate\n");
    ninja_data.push_str("ninja_required_version = 1.9.0\n\n");

    ninja_data.push_str("# Rules\n");
    for rule in &config.rules {
        ninja_data.push_str(&format!("rule {}\n", ninja_escape(&rule.name, true)));
        ninja_data.push_str(&format!("    command = {}\n", ninja_escape(&rule.command, false)));

        if let Some(description) = rule.description.as_ref() {
            ninja_data.push_str(&format!("    description = {}\n", ninja_escape(description, false)));
        }

        match &rule.depstyle {
            DepStyle::Normal => {}
            DepStyle::Gcc => ninja_data.push_str("    deps = gcc\n"),
            DepStyle::Msvc { prefix } => {
                ninja_data.push_str("    deps = msvc\n");
                if let Some(prefix) = prefix {
                    ninja_data.push_str(&format!("    msvc_deps_prefix = {}\n", ninja_escape(&prefix, false)));
                }
            }
        };

        ninja_data.push('\n');
    }

    ninja_data.push_str("# Build Statements\n");
    for build in &config.builds {
        let output = ninja_escape(&build.output.to_string_lossy(), true);
        let inputs = build.input.iter().map(|i| ninja_escape(&i.to_string_lossy(), true)).collect::<Vec<_>>();

        ninja_data.push_str(&format!("build {}: {} {}", output, build.rule.name, inputs.join(" ")));
        if build.implicit_inputs.len() > 0 {
            let implicit_inputs = build
                .implicit_inputs
                .iter()
                .map(|i| ninja_escape(&i.to_string_lossy(), true))
                .collect::<Vec<_>>();
            ninja_data.push_str(&format!(" | {}", implicit_inputs.join(" ")));
        }
        ninja_data.push('\n');

        for (k, v) in build.variables.iter() {
            ninja_data.push_str(&format!("    {} = {}\n", k, ninja_escape(v, true)));
        }

        ninja_data.push('\n');
    }

    ninja_data
}
