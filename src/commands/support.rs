use std::{
    fs::{create_dir_all, write},
    io::stdout,
    path::Path,
};

use anyhow::{Context, Result};
use clap::CommandFactory;
use clap_complete::generate;
use serde_json::json;

use crate::{
    args::{FabricateOptions, SupportCommand},
    config::lua::{EMBEDDED_DIR_MODULES, EMBEDDED_FILE_BUILTINS, EMBEDDED_FILE_HELPERS, EMBEDDED_FILE_META},
};

const LICENSE: &str = include_str!("../../LICENSE");
const THIRD_PARTY: &str = include_str!("../../THIRD_PARTY_NOTICES.md");

pub fn run(command: SupportCommand) -> Result<()> {
    match command {
        SupportCommand::SetupLSP { support_dir } => setup_lua_lsp(&support_dir),
        SupportCommand::Completions { shell } => {
            generate(shell, &mut FabricateOptions::command(), "fabricate".to_string(), &mut stdout());
            Ok(())
        }
        SupportCommand::Licenses => {
            println!("Fabricate license and third party notices\n{}\n{}", LICENSE, THIRD_PARTY);
            Ok(())
        }
    }
}

fn setup_lua_lsp(support_dir: &Path) -> Result<()> {
    let modules_dir = support_dir.join("modules");
    create_dir_all(&modules_dir).context("Failed to make LSP support directory")?;

    for (filename, contents) in [
        ("builtins.lua", EMBEDDED_FILE_BUILTINS),
        ("helpers.lua", EMBEDDED_FILE_HELPERS),
        ("meta.lua", EMBEDDED_FILE_META),
        (".gitignore", "# Generated by Fabricate\n*"),
        (
            "README.txt",
            "This directory (and files within) is generated by Fabricate for lua lsp (LuaLS) integration.\nIt can and will fall out of date over time, at which point it should be re-genereated.\nShould not be committed to git.",
        ),
    ] {
        let filepath = support_dir.join(filename);
        write(&filepath, contents).with_context(|| format!("Failed to write `{}`", filepath.display()))?;
    }

    for file in EMBEDDED_DIR_MODULES.files() {
        let filepath = modules_dir.join(file.path());
        write(&filepath, file.contents()).with_context(|| format!("Failed to write `{}`", filepath.display()))?;
    }

    write(
        ".luarc.json",
        serde_json::to_string_pretty(&json!({
            "$schema": "https://raw.githubusercontent.com/LuaLS/vscode-lua/master/setting/schema.json",
            "workspace.library": [support_dir, modules_dir],
            "workspace.useGitIgnore": true,
            "runtime.builtin": {
                "basic": "enable",
                "coroutine": "disable",
                "debug": "disable",
                "io": "disable",
                "math": "enable",
                "os": "disable",
                "package": "enable",
                "string": "enable",
                "table": "enable",
                "utf8": "disable"
            },
            "workspace.checkThirdParty": false,
            "diagnostics.disable": ["lowercase-global"]
        }))?,
    )
    .context("Failed to write .luarc.json")?;

    eprintln!("Generated `.luarc.json` and `{}`", support_dir.display());

    Ok(())
}
