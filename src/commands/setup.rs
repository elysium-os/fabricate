use std::{
    collections::HashMap,
    fs::{create_dir_all, write},
    io::ErrorKind,
    process::{Command, Stdio},
};

use anyhow::{Context, Result};
use log::debug;
use which::which;

use crate::{
    args::SetupArgs,
    cache::FabricateCache,
    config,
    dependencies::{fetch_dependencies, read_dependencies_file},
    ninja,
};

pub fn run(args: SetupArgs) -> Result<()> {
    let ninja_path = match which("ninja") {
        Err(err) => {
            eprintln!("Warning: failed to locate ninja, cannot cleanup or generate compdb ({})", err);
            None
        }
        Ok(path) => Some(path),
    };

    let project_dir = args
        .project_dir
        .canonicalize()
        .context("Failed to canonicalize project directory path (it likely does not exist)")?;

    debug!("Project directory: {}", project_dir.display());

    let deps_config_path = match project_dir.join(args.deps_config).canonicalize() {
        Ok(path) => Ok(Some(path)),
        Err(err) if err.kind() == ErrorKind::NotFound => Ok(None),
        Err(err) => Err(err),
    }
    .context("Failed to canonicalize dependency config file path (it likely does not exist)")?;

    match &deps_config_path {
        Some(deps_config_path) => debug!("Dependency config file: {}", deps_config_path.display()),
        None => debug!("No dependency config file found"),
    }

    let config_path = project_dir
        .join(args.config)
        .canonicalize()
        .context("Failed to canonicalize config file path (it likely does not exist)")?;

    debug!("Config file: {}", config_path.display());

    // Create build directory
    create_dir_all(&args.build_dir).context("Failed to create build directory")?;

    let build_dir = args.build_dir.canonicalize().context("Failed to canonicalize build directory path")?;

    debug!("Build directory: {}", build_dir.display());

    // Load cache
    let cache_path = build_dir.join("fabricate_cache.toml");
    let cache = FabricateCache::load(&cache_path)?;

    // Fetch dependencies
    eprintln!("Fetching dependencies...");
    let deps = match deps_config_path {
        Some(path) => read_dependencies_file(&path).context("Failed to read dependency config")?,
        None => HashMap::new(),
    };

    let project_deps_dir = project_dir.join("fab-deps");
    let build_deps_dir = build_dir.join("deps");
    create_dir_all(&build_deps_dir).context("Failed to create dependencies directory")?;

    let resolved_project_deps = fetch_dependencies(&project_deps_dir, false, &deps).context("Failed to fetch dependencies")?;
    let resolved_build_deps = fetch_dependencies(
        &build_deps_dir,
        true,
        &deps.into_iter().filter(|(name, _)| !resolved_project_deps.contains_key(name)).collect(),
    )
    .context("Failed to fetch dependencies")?;

    let resolved_deps = HashMap::from_iter(resolved_project_deps.into_iter().chain(resolved_build_deps.into_iter()));

    eprintln!("Dependencies are up-to-date");

    // Evaluate lua config
    eprintln!("Evaluating configuration...");
    let config = config::lua::eval(&project_dir, &build_dir, &config_path, resolved_deps, HashMap::from_iter(args.option))?;

    debug!("Evaluated config\n{:#?}", config);

    // Setup build directory
    write(build_dir.join(".gitignore"), "# Generated by Fabricate\n*").context("Failed to write .gitignore")?;
    write(build_dir.join("build.ninja"), ninja::build_file(&config)).context("Failed to write ninja build file")?;

    // Cleanup build directory
    if let Some(ninja_path) = &ninja_path {
        if cache.is_some() {
            let mut cleanup_cmd = Command::new(ninja_path);
            if let Err(err) = cleanup_cmd.arg("-C").arg(&build_dir).arg("-t").arg("cleandead").status() {
                println!("Warning: ninja cleanup failed ({})", err);
            }
        }
    }

    // Update cache
    let cache = FabricateCache::new(&cache_path, args.prefix, config.installs);
    cache.update()?;

    // Build compdb
    if let Some(ninja_path) = ninja_path {
        let mut compdb_rules = Vec::new();
        for rule in config.rules {
            if !rule.build_compdb {
                continue;
            }

            compdb_rules.push(rule.name.clone());
        }

        if compdb_rules.len() > 0 {
            let mut compdb_cmd = Command::new(ninja_path);
            compdb_cmd.arg("-C").arg(&build_dir).arg("-t").arg("compdb");

            for rule in &compdb_rules {
                compdb_cmd.arg(rule);
            }

            let output = match compdb_cmd.stdout(Stdio::piped()).output() {
                Err(err) => {
                    eprintln!("Warning: ninja compdb failed ({})", err);
                    return Ok(());
                }
                Ok(output) => output,
            };

            write(build_dir.join("compile_commands.json"), output.stdout).context("Failed to write compile_commands.json")?;
        }
    }

    Ok(())
}
